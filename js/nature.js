// ---------- מנוע קטן: כל סבב ממשיך מאיפה שעצרנו, ומה שטעו בו חוזר ----------
// הפריט הבא: מה שטעו בו חוזר אחרי כמה שאלות אחרות, ואחר כך ממשיכים מאיפה שעצרנו בפעם הקודמת
function natNext(kind, list, recent) {
  const s = store.st(CUR.id), st = (s.nat ||= {})[kind] ||= { p: 0, miss: [] };
  const rnd = seeded(CUR.id + kind), order = list.map((_, i) => i);
  for (let i = order.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [order[i], order[j]] = [order[j], order[i]]; }
  const near = recent.slice(-4), back = st.miss.find(i => i < list.length && !near.includes(i));
  if (back !== undefined && recent.length % 3 === 2) { recent.push(back); return back; }
  let i, t = 0; do { i = order[st.p++ % order.length]; } while (near.includes(i) && ++t < 10);
  store.save(); recent.push(i); return i;
}
function natMark(kind, i, ok) {
  const st = store.st(CUR.id).nat[kind]; st.miss = st.miss.filter(x => x !== i); if (!ok) st.miss.push(i); store.save();
}
